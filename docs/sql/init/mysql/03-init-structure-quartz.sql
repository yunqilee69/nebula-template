--      - 单体应用（默认）：应用库即调度库，脚本随业务库初始化一起执行（docker-compose 已挂载）。
--      - 调度器独立部署：对调度服务自身的数据源执行本脚本；
--        若使用独立库，需先 createdb/建库并授权，再连到该库执行。
--   3. 仅 Quartz + JDBC 持久化（org.quartz.jobStore.class=JobStoreTX）时需要执行；
