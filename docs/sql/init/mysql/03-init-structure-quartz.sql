SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

CREATE TABLE IF NOT EXISTS QRTZ_JOB_DETAILS (
    SCHED_NAME VARCHAR(120) NOT NULL COMMENT '调度器名称',
    JOB_NAME VARCHAR(200) NOT NULL COMMENT '任务名称',
    JOB_GROUP VARCHAR(200) NOT NULL COMMENT '任务组',
    DESCRIPTION VARCHAR(250) DEFAULT NULL COMMENT '描述',
    JOB_CLASS_NAME VARCHAR(250) NOT NULL COMMENT '任务类全限定名',
    IS_DURABLE VARCHAR(1) NOT NULL COMMENT '是否持久化',
    IS_NONCONCURRENT VARCHAR(1) NOT NULL COMMENT '是否禁止并发',
    IS_UPDATE_DATA VARCHAR(1) NOT NULL COMMENT '是否更新数据',
    REQUESTS_RECOVERY VARCHAR(1) NOT NULL COMMENT '是否请求故障恢复',
    JOB_DATA BLOB DEFAULT NULL COMMENT '任务数据',
    PRIMARY KEY (SCHED_NAME, JOB_NAME, JOB_GROUP),
    KEY IDX_QRTZ_J_REQ_RECOVERY (SCHED_NAME, REQUESTS_RECOVERY),
    KEY IDX_QRTZ_J_GRP (SCHED_NAME, JOB_GROUP)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Quartz任务定义表';

CREATE TABLE IF NOT EXISTS QRTZ_TRIGGERS (
    SCHED_NAME VARCHAR(120) NOT NULL COMMENT '调度器名称',
    TRIGGER_NAME VARCHAR(200) NOT NULL COMMENT '触发器名称',
    TRIGGER_GROUP VARCHAR(200) NOT NULL COMMENT '触发器组',
    JOB_NAME VARCHAR(200) NOT NULL COMMENT '任务名称',
    JOB_GROUP VARCHAR(200) NOT NULL COMMENT '任务组',
    DESCRIPTION VARCHAR(250) DEFAULT NULL COMMENT '描述',
    NEXT_FIRE_TIME BIGINT DEFAULT NULL COMMENT '下次触发时间',
    PREV_FIRE_TIME BIGINT DEFAULT NULL COMMENT '上次触发时间',
    PRIORITY INTEGER DEFAULT NULL COMMENT '优先级',
    TRIGGER_STATE VARCHAR(16) NOT NULL COMMENT '触发器状态',
    TRIGGER_TYPE VARCHAR(8) NOT NULL COMMENT '触发器类型',
    START_TIME BIGINT NOT NULL COMMENT '开始时间',
    END_TIME BIGINT DEFAULT NULL COMMENT '结束时间',
    CALENDAR_NAME VARCHAR(200) DEFAULT NULL COMMENT '日历名称',
    MISFIRE_INSTR SMALLINT DEFAULT NULL COMMENT '错过触发策略',
    JOB_DATA BLOB DEFAULT NULL COMMENT '任务数据',
    KEY IDX_QRTZ_T_J (SCHED_NAME, JOB_NAME, JOB_GROUP),
    KEY IDX_QRTZ_T_JG (SCHED_NAME, JOB_GROUP),
    KEY IDX_QRTZ_T_C (SCHED_NAME, CALENDAR_NAME),
    KEY IDX_QRTZ_T_G (SCHED_NAME, TRIGGER_GROUP),
    KEY IDX_QRTZ_T_STATE (SCHED_NAME, TRIGGER_STATE),
    KEY IDX_QRTZ_T_N_STATE (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP, TRIGGER_STATE),
    KEY IDX_QRTZ_T_N_G_STATE (SCHED_NAME, TRIGGER_GROUP, TRIGGER_STATE),
    KEY IDX_QRTZ_T_NEXT_FIRE_TIME (SCHED_NAME, NEXT_FIRE_TIME),
    KEY IDX_QRTZ_T_NFT_ST (SCHED_NAME, TRIGGER_STATE, NEXT_FIRE_TIME),
    KEY IDX_QRTZ_T_NFT_MISFIRE (SCHED_NAME, MISFIRE_INSTR, NEXT_FIRE_TIME),
    KEY IDX_QRTZ_T_NFT_ST_MISFIRE (SCHED_NAME, MISFIRE_INSTR, NEXT_FIRE_TIME, TRIGGER_STATE),
    KEY IDX_QRTZ_T_NFT_ST_MISFIRE_GRP (SCHED_NAME, MISFIRE_INSTR, NEXT_FIRE_TIME, TRIGGER_GROUP, TRIGGER_STATE),
    PRIMARY KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP),
    CONSTRAINT FK_QRTZ_TRIGGERS_JOB_DETAILS FOREIGN KEY (SCHED_NAME, JOB_NAME, JOB_GROUP)
        REFERENCES QRTZ_JOB_DETAILS (SCHED_NAME, JOB_NAME, JOB_GROUP)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Quartz触发器表';

CREATE TABLE IF NOT EXISTS QRTZ_SIMPLE_TRIGGERS (
    SCHED_NAME VARCHAR(120) NOT NULL COMMENT '调度器名称',
    TRIGGER_NAME VARCHAR(200) NOT NULL COMMENT '触发器名称',
    TRIGGER_GROUP VARCHAR(200) NOT NULL COMMENT '触发器组',
    REPEAT_COUNT BIGINT NOT NULL COMMENT '重复次数',
    REPEAT_INTERVAL BIGINT NOT NULL COMMENT '重复间隔',
    TIMES_TRIGGERED BIGINT NOT NULL COMMENT '已触发次数',
    PRIMARY KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP),
    CONSTRAINT FK_QRTZ_SIMPLE_TRIGGERS FOREIGN KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP)
        REFERENCES QRTZ_TRIGGERS (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Quartz简单触发器表';

CREATE TABLE IF NOT EXISTS QRTZ_CRON_TRIGGERS (
    SCHED_NAME VARCHAR(120) NOT NULL COMMENT '调度器名称',
    TRIGGER_NAME VARCHAR(200) NOT NULL COMMENT '触发器名称',
    TRIGGER_GROUP VARCHAR(200) NOT NULL COMMENT '触发器组',
    CRON_EXPRESSION VARCHAR(120) NOT NULL COMMENT 'Cron表达式',
    TIME_ZONE_ID VARCHAR(80) DEFAULT NULL COMMENT '时区ID',
    PRIMARY KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP),
    CONSTRAINT FK_QRTZ_CRON_TRIGGERS FOREIGN KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP)
        REFERENCES QRTZ_TRIGGERS (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Quartz Cron触发器表';

CREATE TABLE IF NOT EXISTS QRTZ_SIMPROP_TRIGGERS (
    SCHED_NAME VARCHAR(120) NOT NULL COMMENT '调度器名称',
    TRIGGER_NAME VARCHAR(200) NOT NULL COMMENT '触发器名称',
    TRIGGER_GROUP VARCHAR(200) NOT NULL COMMENT '触发器组',
    STR_PROP_1 VARCHAR(512) DEFAULT NULL COMMENT '字符串属性1',
    STR_PROP_2 VARCHAR(512) DEFAULT NULL COMMENT '字符串属性2',
    STR_PROP_3 VARCHAR(512) DEFAULT NULL COMMENT '字符串属性3',
    INT_PROP_1 INTEGER DEFAULT NULL COMMENT '整数属性1',
    INT_PROP_2 INTEGER DEFAULT NULL COMMENT '整数属性2',
    LONG_PROP_1 BIGINT DEFAULT NULL COMMENT '长整数属性1',
    LONG_PROP_2 BIGINT DEFAULT NULL COMMENT '长整数属性2',
    DEC_PROP_1 NUMERIC(13,4) DEFAULT NULL COMMENT '小数属性1',
    DEC_PROP_2 NUMERIC(13,4) DEFAULT NULL COMMENT '小数属性2',
    BOOL_PROP_1 VARCHAR(1) DEFAULT NULL COMMENT '布尔属性1',
    BOOL_PROP_2 VARCHAR(1) DEFAULT NULL COMMENT '布尔属性2',
    PRIMARY KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP),
    CONSTRAINT FK_QRTZ_SIMPROP_TRIGGERS FOREIGN KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP)
        REFERENCES QRTZ_TRIGGERS (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Quartz简单属性触发器表';

CREATE TABLE IF NOT EXISTS QRTZ_BLOB_TRIGGERS (
    SCHED_NAME VARCHAR(120) NOT NULL COMMENT '调度器名称',
    TRIGGER_NAME VARCHAR(200) NOT NULL COMMENT '触发器名称',
    TRIGGER_GROUP VARCHAR(200) NOT NULL COMMENT '触发器组',
    BLOB_DATA BLOB DEFAULT NULL COMMENT '触发器数据',
    PRIMARY KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP),
    CONSTRAINT FK_QRTZ_BLOB_TRIGGERS FOREIGN KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP)
        REFERENCES QRTZ_TRIGGERS (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Quartz Blob触发器表';

CREATE TABLE IF NOT EXISTS QRTZ_CALENDARS (
    SCHED_NAME VARCHAR(120) NOT NULL COMMENT '调度器名称',
    CALENDAR_NAME VARCHAR(200) NOT NULL COMMENT '日历名称',
    CALENDAR BLOB NOT NULL COMMENT '日历数据',
    PRIMARY KEY (SCHED_NAME, CALENDAR_NAME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Quartz日历表';

CREATE TABLE IF NOT EXISTS QRTZ_PAUSED_TRIGGER_GRPS (
    SCHED_NAME VARCHAR(120) NOT NULL COMMENT '调度器名称',
    TRIGGER_GROUP VARCHAR(200) NOT NULL COMMENT '触发器组',
    PRIMARY KEY (SCHED_NAME, TRIGGER_GROUP)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Quartz暂停触发器组表';

CREATE TABLE IF NOT EXISTS QRTZ_FIRED_TRIGGERS (
    SCHED_NAME VARCHAR(120) NOT NULL COMMENT '调度器名称',
    ENTRY_ID VARCHAR(95) NOT NULL COMMENT '执行条目ID',
    TRIGGER_NAME VARCHAR(200) NOT NULL COMMENT '触发器名称',
    TRIGGER_GROUP VARCHAR(200) NOT NULL COMMENT '触发器组',
    INSTANCE_NAME VARCHAR(200) NOT NULL COMMENT '调度实例名称',
    FIRED_TIME BIGINT NOT NULL COMMENT '触发时间',
    SCHED_TIME BIGINT NOT NULL COMMENT '调度时间',
    PRIORITY INTEGER NOT NULL COMMENT '优先级',
    STATE VARCHAR(16) NOT NULL COMMENT '状态',
    JOB_NAME VARCHAR(200) DEFAULT NULL COMMENT '任务名称',
    JOB_GROUP VARCHAR(200) DEFAULT NULL COMMENT '任务组',
    IS_NONCONCURRENT VARCHAR(1) DEFAULT NULL COMMENT '是否禁止并发',
    REQUESTS_RECOVERY VARCHAR(1) DEFAULT NULL COMMENT '是否请求故障恢复',
    KEY IDX_QRTZ_FT_TRIG_INST_NAME (SCHED_NAME, INSTANCE_NAME),
    KEY IDX_QRTZ_FT_INST_JOB_REQ_RCVRY (SCHED_NAME, INSTANCE_NAME, REQUESTS_RECOVERY),
    KEY IDX_QRTZ_FT_J_G (SCHED_NAME, JOB_NAME, JOB_GROUP),
    KEY IDX_QRTZ_FT_JG (SCHED_NAME, JOB_GROUP),
    KEY IDX_QRTZ_FT_T_G (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP),
    KEY IDX_QRTZ_FT_TG (SCHED_NAME, TRIGGER_GROUP),
    PRIMARY KEY (SCHED_NAME, ENTRY_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Quartz已触发记录表';

CREATE TABLE IF NOT EXISTS QRTZ_SCHEDULER_STATE (
    SCHED_NAME VARCHAR(120) NOT NULL COMMENT '调度器名称',
    INSTANCE_NAME VARCHAR(200) NOT NULL COMMENT '调度实例名称',
    LAST_CHECKIN_TIME BIGINT NOT NULL COMMENT '最后检查时间',
    CHECKIN_INTERVAL BIGINT NOT NULL COMMENT '检查间隔',
    PRIMARY KEY (SCHED_NAME, INSTANCE_NAME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Quartz调度器状态表';

CREATE TABLE IF NOT EXISTS QRTZ_LOCKS (
    SCHED_NAME VARCHAR(120) NOT NULL COMMENT '调度器名称',
    LOCK_NAME VARCHAR(40) NOT NULL COMMENT '锁名称',
    PRIMARY KEY (SCHED_NAME, LOCK_NAME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Quartz锁表';

SET FOREIGN_KEY_CHECKS = 1;